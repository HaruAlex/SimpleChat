
package simplechat;

/**
 * Interface định nghĩa phương thức hiển thị thông báo
 * cho các thành phần trong ứng dụng SimpleChat.
 */
public interface ChatIF {

    /**
     * Hiển thị thông báo ra màn hình console.
     *
     * @param message nội dung cần hiển thị
     */
    public void display(String message);
}
